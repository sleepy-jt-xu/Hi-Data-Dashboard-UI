import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const directory = dirname(fileURLToPath(import.meta.url));
const sourceDirectory = join(directory, "../assets/icons/source");

// The design files use one ink color; it becomes currentColor so the site can recolor icons.
const INK_COLOR = /#453D53/gi;

function normalize(markup, file) {
  const svg = markup
    .replace(/<\?xml[^>]*>/g, "")
    // Figma exports a white background rect; drop it so the icon is transparent.
    .replace(/<rect\b[^>]*fill="white"[^>]*\/>/gi, "")
    .replace(INK_COLOR, "currentColor")
    .replace(/<svg\b([^>]*)>/i, (tag, attrs) =>
      `<svg${attrs.replace(/\s(width|height)="[^"]*"/g, "")}>`
    )
    .replace(/\s*\n\s*/g, "")
    .trim();

  const leftover = svg.match(/#[0-9a-f]{3,8}\b/gi);
  if (leftover) {
    console.warn(`  ${file}: unexpected colors kept as-is (${[...new Set(leftover)].join(", ")})`);
  }
  return svg;
}

export async function buildIconsScript() {
  const files = (await readdir(sourceDirectory))
    .filter((file) => file.toLowerCase().endsWith(".svg"))
    .sort((a, b) => a.localeCompare(b));

  const icons = await Promise.all(
    files.map(async (file) => ({
      id: basename(file, ".svg").trim().replace(/\s+/g, "-").toLowerCase(),
      svg: normalize(await readFile(join(sourceDirectory, file), "utf8"), file)
    }))
  );

  const script =
    "// Generated by import-icons.mjs from assets/icons/source. Do not edit by hand.\n" +
    `window.REPORT_UI_ICONS = ${JSON.stringify(icons, null, 2)};\n`;
  await writeFile(join(directory, "icons.js"), script);
  console.log(`Imported ${icons.length} icons into site/icons.js`);
  return script;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await buildIconsScript();
}
