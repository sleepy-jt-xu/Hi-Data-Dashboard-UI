import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildIconsScript } from "./import-icons.mjs";

const directory = dirname(fileURLToPath(import.meta.url));
const icons = await buildIconsScript();
const [html, styleSource, catalog, app, interFont] = await Promise.all([
  readFile(join(directory, "index.html"), "utf8"),
  readFile(join(directory, "styles.css"), "utf8"),
  readFile(join(directory, "catalog.js"), "utf8"),
  readFile(join(directory, "app.js"), "utf8"),
  readFile(join(directory, "assets/fonts/InterVariable.ttf"))
]);

const logo = await readFile(join(directory, "../assets/logo.svg"));
const logoDataUrl = `data:image/svg+xml;base64,${logo.toString("base64")}`;
const background = await readFile(join(directory, "../assets/digital-store-bg.png"));
const backgroundDataUrl = `data:image/png;base64,${background.toString("base64")}`;
const appSource = app
  .replace('"../assets/logo.svg"', JSON.stringify(logoDataUrl))
  .replace('"../assets/digital-store-bg.png"', JSON.stringify(backgroundDataUrl));

const interDataUrl = `data:font/ttf;base64,${interFont.toString("base64")}`;
const styles = styleSource.replace(
  "./assets/fonts/InterVariable.ttf",
  interDataUrl
);

const safeScript = (content) => content.replaceAll("</script", "<\\/script");
const standalone = html
  .replace(
    '<link rel="stylesheet" href="./styles.css" />',
    `<style>\n${styles}\n</style>`
  )
  .replace(
    '<script src="./icons.js"></script>',
    `<script>\n${safeScript(icons)}\n</script>`
  )
  .replace(
    '<script src="./catalog.js"></script>',
    `<script>\n${safeScript(catalog)}\n</script>`
  )
  .replace(
    '<script src="./app.js"></script>',
    `<script>\n${safeScript(appSource)}\n</script>`
  )
  .replace(
    "<!doctype html>",
    "<!doctype html>\n<!-- Generated by build-standalone.mjs. Edit the source files, not this file. -->"
  );

// Written to the skill root so users can open it directly.
await writeFile(join(directory, "..", "Hidata-dashboard-ui.html"), standalone);
console.log("Built Hidata-dashboard-ui.html");
